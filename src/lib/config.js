/**
 * 开发配置。打包时 scripts/package.mjs 会用 config.prod.js 覆盖本文件，
 * 生产包里不存在这个文件。
 *
 * 全部可调参数集中在这里，方便一处修改、全局生效。
 *
 * 请求相关参数取值偏保守：豆瓣的收藏接口是非公开接口，
 * 公开分发后使用者变多，过密的请求更容易被限流或触发风控。
 */

export const CONFIG = {
  /** 单页拉取条数，实测 50 生效 */
  pageSize: 50,

  /** 相邻分页请求的间隔。公开版本从 800ms 上调到 1200ms */
  pageIntervalMs: 1200,

  /** 单个维度的最大页数，防御性上限 */
  maxPages: 200,

  /**
   * 允许同时拉取几个维度。每个维度内部仍然是串行分页（间隔 pageIntervalMs），
   * 只是不同的维度可以并行，把总耗时从「维度数 × 页数 × 间隔」降下来。
   * 不要超过维度总数（目前 2 个）。
   */
  maxConcurrentDimensions: 2,

  /** 缓存新鲜期：超过即视为过期，打开界面时后台刷新 */
  cacheTtlMs: 24 * 60 * 60 * 1000,

  /**
   * 最短更新频率。优先级高于手动同步：
   * 距离上次成功同步不足该时长时，即使点「同步」也会被拒绝。
   * 目的不是省流量，而是给公开分发后的请求密度设一个硬下限。
   *
   * 调试期临时调成 1 分钟，上线前改回 10 * 60 * 1000。
   */
  minRefreshMs: 60 * 1000,

  /** 每个类别每天最多跳过几次。调试期可以调大。 */
  dailySkipLimit: 1,

  /** 历史记录保留上限 */
  historyLimit: 500,

  /** 默认去重窗口（最近 N 条不重复抽到） */
  dedupeWindow: 20,
}
